"""Generate runtime/chemtable.h from the reference data in chem/elements.py.

The device parses formulas with the same atomic weights, ion charges and name
table the Python reference uses, so the C parser needs that data as compiled
constants. Generating the header is what keeps it from becoming a second copy:
`--check` fails when the header has drifted, exactly like `export_relations.py`
does for the relation table.

    python3 export_chem.py           # rewrite runtime/chemtable.h
    python3 export_chem.py --check   # exit 1 if the header is stale
"""
import argparse
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)

from chem.elements import (  # noqa: E402
    ATOMIC_WEIGHTS,
    FIXED_CATION_CHARGES,
    METALS,
    MONATOMIC_ANION_CHARGES,
    NAMES,
    POLYATOMIC_ANIONS,
    POLYATOMIC_CATIONS,
)

DEFAULT_HEADER = os.path.join(ROOT, "runtime", "chemtable.h")


def rows():
    elements = []
    for symbol, weight in ATOMIC_WEIGHTS.items():
        if symbol in METALS:
            elements.append((symbol, weight,
                             FIXED_CATION_CHARGES.get(symbol, 0)))
        else:
            elements.append((symbol, weight, -1))
    return (
        elements,
        sorted(POLYATOMIC_ANIONS.items()),
        sorted(MONATOMIC_ANION_CHARGES.items()),
        sorted(POLYATOMIC_CATIONS.items()),
        sorted(NAMES.items()),
    )


def source_sha(table):
    return hashlib.sha256(json.dumps(table).encode()).hexdigest()[:16]


def cstr(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def render(table):
    elements, anions, mono, cations, names = table
    lines = [
        "/*",
        " * Generated by export_chem.py from chem/elements.py. Do not edit by",
        " * hand: the C parser and the Python reference answer from these rows,",
        " * and a hand-edited copy is how they stop agreeing.",
        " *",
        " * CHEM_SOURCE_SHA %s" % source_sha(table),
        " */",
        "#ifndef CHEMTABLE_H",
        "#define CHEMTABLE_H",
        "",
        "#include <stdint.h>",
        "",
        "#define CHEM_NUM_ELEMENTS %d" % len(elements),
        "#define CHEM_NUM_ANIONS %d" % len(anions),
        "#define CHEM_NUM_MONO_ANIONS %d" % len(mono),
        "#define CHEM_NUM_CATIONS %d" % len(cations),
        "#define CHEM_NUM_NAMES %d" % len(names),
        "",
        "typedef struct {",
        "\tconst char *symbol;",
        "\tuint32_t weight_mg;",
        "\t/* A fixed cation charge; 0 when a formula settles it; -1 for a",
        "\t * nonmetal, which cannot lead an ionic formula here. */",
        "\tint8_t cation_charge;",
        "} chem_element_t;",
        "",
        "typedef struct {",
        "\tconst char *formula;",
        "\tuint8_t charge;",
        "} chem_ion_t;",
        "",
        "typedef struct {",
        "\tconst char *name;",
        "\tconst char *formula;",
        "} chem_name_t;",
        "",
        "#ifdef CHEMTABLE_IMPL",
        "const chem_element_t chem_elements[CHEM_NUM_ELEMENTS] = {",
    ]
    for symbol, weight, charge in elements:
        lines.append('\t{"%s", %d, %d},' % (cstr(symbol), weight, charge))
    lines += [
        "};",
        "",
        "const chem_ion_t chem_anions[CHEM_NUM_ANIONS] = {",
    ]
    for formula, charge in anions:
        lines.append('\t{"%s", %d},' % (cstr(formula), charge))
    lines += [
        "};",
        "",
        "const chem_ion_t chem_mono_anions[CHEM_NUM_MONO_ANIONS] = {",
    ]
    for symbol, charge in mono:
        lines.append('\t{"%s", %d},' % (cstr(symbol), charge))
    lines += [
        "};",
        "",
        "const chem_ion_t chem_cations[CHEM_NUM_CATIONS] = {",
    ]
    for formula, charge in cations:
        lines.append('\t{"%s", %d},' % (cstr(formula), charge))
    lines += [
        "};",
        "",
        "const chem_name_t chem_names[CHEM_NUM_NAMES] = {",
    ]
    for name, formula in names:
        lines.append('\t{"%s", "%s"},' % (cstr(name), cstr(formula)))
    lines += [
        "};",
        "#else",
        "extern const chem_element_t chem_elements[CHEM_NUM_ELEMENTS];",
        "extern const chem_ion_t chem_anions[CHEM_NUM_ANIONS];",
        "extern const chem_ion_t chem_mono_anions[CHEM_NUM_MONO_ANIONS];",
        "extern const chem_ion_t chem_cations[CHEM_NUM_CATIONS];",
        "extern const chem_name_t chem_names[CHEM_NUM_NAMES];",
        "#endif",
        "",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--header", default=DEFAULT_HEADER)
    ap.add_argument("--check", action="store_true",
                    help="fail if the header is stale instead of rewriting it")
    args = ap.parse_args()

    table = rows()
    want = render(table)
    if args.check:
        if not os.path.exists(args.header):
            print("STALE: %s does not exist" % args.header)
            print("Run: python3 export_chem.py")
            return 1
        with open(args.header) as f:
            got = f.read()
        if got != want:
            print("STALE: %s does not match chem/elements.py" % args.header)
            print("Run: python3 export_chem.py")
            return 1
        print("ok: chemtable.h matches chem/elements.py (%d elements, %d names, sha %s)"
              % (len(table[0]), len(table[4]), source_sha(table)))
        return 0

    if os.path.exists(args.header):
        with open(args.header) as f:
            if f.read() == want:
                print("chemtable.h already matches chem/elements.py; not rewritten")
                return 0
    with open(args.header, "w") as f:
        f.write(want)
    print("wrote %d elements, %d anions, %d names into %s"
          % (len(table[0]), len(table[1]) + len(table[2]), len(table[4]),
             args.header))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
