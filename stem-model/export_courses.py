"""Export the course map as a C header the device picker can read.

`courses.py` is the only place that knows which topic belongs to which course and
unit, and it is Python. The picker runs in C on the device, so the map has to be
generated rather than duplicated: a second hand-written copy of a 134-topic table
would be wrong within a week, and wrong here means offering a student a call the
catalogue does not have.

Three rules this exporter enforces rather than documents:

  - a topic recorded as a gap is exported as a gap, never as a relation, so the
    picker cannot promise what the catalogue cannot answer;
  - a typed topic keeps its command and is not filed under a relation id, because
    the typed engine answers it and no relation does;
  - every relation id comes from `reltable.h`, so the picker and the decoder
    cannot disagree about what a name means.

`--check` re-renders and compares, which is what `gate.sh` runs: a generated
artifact no gate checks is how this repository shipped a stale tokenizer.
"""

import argparse
import hashlib
import os
import sys

import courses
from relations import RELATIONS

OUT = "runtime/coursetable.h"


def relation_ids():
    """Relation name -> decoder id, read from the table the decoder uses."""

    path = "runtime/reltable.h"
    ids = {}
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if not line.startswith('{"'):
            continue
        parts = line.split('"')
        name = parts[1]
        rest = [p.strip() for p in line.split('",')]
        try:
            ids[name] = int(rest[1].split(",")[0])
        except (IndexError, ValueError):
            continue
    if not ids:
        raise SystemExit(f"no relation ids found in {path}")
    return ids


def render():
    ids = relation_ids()
    lines = []
    add = lines.append

    course_rows = []
    unit_rows = []
    topic_rows = []
    for c_index, (code, entry) in enumerate(courses.COURSES.items()):
        first_unit = len(unit_rows)
        for unit in entry.units:
            first_topic = len(topic_rows)
            for topic in unit.topics:
                kind, value = topic.serves
                if kind == "relation":
                    if value not in ids:
                        raise SystemExit(f"{code}: {value} is not a relation")
                    topic_rows.append((1, ids[value], topic.topic))
                elif kind == "typed":
                    topic_rows.append((2, 0, topic.topic))
                else:
                    topic_rows.append((0, 0, topic.topic))
            unit_rows.append((c_index, unit.number, unit.title,
                              first_topic, len(topic_rows) - first_topic))
        course_rows.append((code, entry.name, entry.exact_floor, first_unit,
                            len(unit_rows) - first_unit))

    digest = hashlib.sha256()
    for c in course_rows:
        digest.update(repr(c).encode())
    for u in unit_rows:
        digest.update(repr(u).encode())
    for t in topic_rows:
        digest.update(repr(t).encode())

    add("/*")
    add(" * Generated by export_courses.py from courses.py. Do not edit by hand.")
    add(" * The picker walks this table, so a stale row offers the student a")
    add(" * topic the catalogue no longer answers.")
    add(" *")
    add(f" * CRS_SOURCE_SHA {digest.hexdigest()[:16]}")
    add(" */")
    add("#ifndef COURSETABLE_H")
    add("#define COURSETABLE_H")
    add("")
    add("#include <stdint.h>")
    add("")
    add(f"#define CRS_NUM_COURSES {len(course_rows)}")
    add(f"#define CRS_NUM_UNITS {len(unit_rows)}")
    add(f"#define CRS_NUM_TOPICS {len(topic_rows)}")
    add("")
    add("/* kind: 0 gap, 1 relation (id in rel), 2 typed engine. A course with")
    add(" * floor 0.0 is reported and not judged. */")
    add("typedef struct {")
    add("\tconst char *code;")
    add("\tconst char *name;")
    add("\tfloat floor;")
    add("\tuint16_t first_unit;")
    add("\tuint16_t num_units;")
    add("} crs_course_t;")
    add("")
    add("typedef struct {")
    add("\tuint8_t course;")
    add("\tconst char *number;")
    add("\tconst char *title;")
    add("\tuint16_t first_topic;")
    add("\tuint16_t num_topics;")
    add("} crs_unit_t;")
    add("")
    add("typedef struct {")
    add("\tuint8_t kind;")
    add("\tuint16_t rel;")
    add("\tconst char *topic;")
    add("} crs_topic_t;")
    add("")
    add("#ifdef COURSETABLE_IMPL")
    add("const crs_course_t crs_courses[CRS_NUM_COURSES] = {")
    for code, name, floor, first, count in course_rows:
        shown = 0.0 if floor is None else floor
        add(f'\t{{"{code}", "{name}", {shown:.1f}f, {first}, {count}}},')
    add("};")
    add("")
    add("const crs_unit_t crs_units[CRS_NUM_UNITS] = {")
    for c_index, number, title, first, count in unit_rows:
        add(f'\t{{{c_index}, "{number}", "{title}", {first}, {count}}},')
    add("};")
    add("")
    add("const crs_topic_t crs_topics[CRS_NUM_TOPICS] = {")
    for kind, rel, topic in topic_rows:
        add(f'\t{{{kind}, {rel}, "{topic}"}},')
    add("};")
    add("#endif")
    add("")
    add("#endif")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--check", action="store_true",
                    help="fail if the committed header is stale")
    args = ap.parse_args()

    text = render()
    if args.check:
        if not os.path.exists(args.out):
            raise SystemExit(f"{args.out} is missing; run export_courses.py")
        current = open(args.out, encoding="utf-8").read()
        if current != text:
            raise SystemExit(f"{args.out} is stale; run export_courses.py")
        print(f"ok: {args.out} matches courses.py")
        return 0

    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {len(courses.COURSES)} courses, {courses.all_count()[0]} topics"
          f" into {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
