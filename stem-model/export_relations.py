"""Generate runtime/reltable.h from relations.py.

The decoder masks token ids, so the C runtime has to know exactly which ids
name a relation and in which order the tokenizer assigns them. A hand-kept
copy has the same failure mode as a stale bpe.h: it compiles, passes the unit
tests, and silently masks the wrong tokens. Generate it instead, and make
--check fail when the checked-in header has drifted.

    python3 export_relations.py           # rewrite runtime/reltable.h
    python3 export_relations.py --check   # exit 1 if it is stale, write nothing
"""
import argparse
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)

from relations import RELATIONS  # noqa: E402
from tokenizer import REL_BASE  # noqa: E402

DEFAULT_HEADER = os.path.join(ROOT, "runtime", "reltable.h")


def rows():
    """(name, arity, token id) per relation, in tokenizer id order."""
    return [(name, len(RELATIONS[name].params), REL_BASE + i)
            for i, name in enumerate(sorted(RELATIONS))]


def source_sha(rows):
    return hashlib.sha256(json.dumps(rows).encode()).hexdigest()[:16]


def render(rows):
    lines = [
        "/*",
        " * Generated by export_relations.py from relations.py. Do not edit by hand.",
        " * The decoder masks relation ids from this table, so a stale row masks the",
        " * wrong token instead of failing loudly.",
        " *",
        " * REL_SOURCE_SHA %s" % source_sha(rows),
        " */",
        "#ifndef RELTABLE_H",
        "#define RELTABLE_H",
        "",
        "#include <stdint.h>",
        "",
        "#define REL_NUM_RELATIONS %d" % len(rows),
        "#define REL_FIRST_ID %d" % REL_BASE,
        "",
        "typedef struct {",
        "\tconst char *name;",
        "\tunsigned char arity;",
        "\tuint16_t id;",
        "} rel_row_t;",
        "",
        "#ifdef RELTABLE_IMPL",
        "const rel_row_t rel_rows[REL_NUM_RELATIONS] = {",
    ]
    for name, arity, idx in rows:
        lines.append('\t{"%s", %d, %d},' % (name, arity, idx))
    lines += [
        "};",
        "#else",
        "extern const rel_row_t rel_rows[REL_NUM_RELATIONS];",
        "#endif",
        "",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--header", default=DEFAULT_HEADER)
    ap.add_argument("--check", action="store_true",
                    help="fail if the header is stale instead of rewriting it")
    args = ap.parse_args()

    table = rows()
    want = render(table)
    if args.check:
        if not os.path.exists(args.header):
            print("STALE: %s does not exist" % args.header)
            print("Run: python3 export_relations.py")
            return 1
        with open(args.header) as f:
            got = f.read()
        if got != want:
            print("STALE: %s does not match relations.py" % args.header)
            print("Run: python3 export_relations.py")
            return 1
        print("ok: reltable.h matches relations.py (%d relations, sha %s)"
              % (len(table), source_sha(table)))
        return 0

    if os.path.exists(args.header):
        with open(args.header) as f:
            if f.read() == want:
                print("reltable.h already matches relations.py; not rewritten")
                return 0
    with open(args.header, "w") as f:
        f.write(want)
    print("wrote %d relations into %s (REL_FIRST_ID=%d, sha %s)"
          % (len(table), args.header, REL_BASE, source_sha(table)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
