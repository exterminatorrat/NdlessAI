"""Generate runtime/steptable.h from the relations' step templates.

Each relation may carry a short display of its working: the formula as written
on paper, and the same formula as arithmetic over its arguments. The device
shows both, and `check_steps.py` proves the arithmetic reproduces the solver's
own answer, so the table is checked data rather than prose.

    python3 export_steps.py           # rewrite runtime/steptable.h
    python3 export_steps.py --check   # exit 1 if it is stale, write nothing
"""
import argparse
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)

from relations import RELATIONS  # noqa: E402

DEFAULT_HEADER = os.path.join(ROOT, "runtime", "steptable.h")


def rows():
    """(name, line, expr) per relation that shows working, name-sorted."""
    out = []
    for name in sorted(RELATIONS):
        step = RELATIONS[name].step
        if not step.get("line") or not step.get("expr"):
            continue
        out.append((name, step["line"], step["expr"]))
    return out


def source_sha(table):
    return hashlib.sha256(json.dumps(table).encode()).hexdigest()[:16]


def cstr(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def render(table):
    lines = [
        "/*",
        " * Generated by export_steps.py from the step templates in relations/.",
        " * Do not edit by hand: check_steps.py proves each template reproduces",
        " * its solver's answer, and a hand-edited copy is not covered by that.",
        " *",
        " * STEP_SOURCE_SHA %s" % source_sha(table),
        " */",
        "#ifndef STEPTABLE_H",
        "#define STEPTABLE_H",
        "",
        "#include <stdint.h>",
        "",
        "#define STEP_NUM_ROWS %d" % len(table),
        "",
        "typedef struct {",
        "\tconst char *name;",
        "\tconst char *line;",
        "\tconst char *expr;",
        "} step_row_t;",
        "",
        "#ifdef STEPTABLE_IMPL",
        "const step_row_t step_rows[STEP_NUM_ROWS] = {",
    ]
    for name, line, expr in table:
        lines.append('\t{"%s", "%s", "%s"},' % (cstr(name), cstr(line), cstr(expr)))
    lines += [
        "};",
        "#else",
        "extern const step_row_t step_rows[STEP_NUM_ROWS];",
        "#endif",
        "",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--header", default=DEFAULT_HEADER)
    ap.add_argument("--check", action="store_true",
                    help="fail if the header is stale instead of rewriting it")
    args = ap.parse_args()

    table = rows()
    want = render(table)
    if args.check:
        if not os.path.exists(args.header):
            print("STALE: %s does not exist" % args.header)
            print("Run: python3 export_steps.py")
            return 1
        with open(args.header) as f:
            if f.read() != want:
                print("STALE: %s does not match the relations' step templates"
                      % args.header)
                print("Run: python3 export_steps.py")
                return 1
        print("ok: steptable.h matches the step templates (%d rows, sha %s)"
              % (len(table), source_sha(table)))
        return 0

    if os.path.exists(args.header):
        with open(args.header) as f:
            if f.read() == want:
                print("steptable.h already matches the step templates; not rewritten")
                return 0
    with open(args.header, "w") as f:
        f.write(want)
    print("wrote %d step templates into %s (sha %s)"
          % (len(table), args.header, source_sha(table)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
