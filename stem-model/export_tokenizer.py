import json
import os
import sys
import hashlib

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)

from tokenizer import FIRST_MERGE, SPECIALS, SPECIAL_PIECES

BEGIN = "/* BPE_DATA_BEGIN"
END = "/* BPE_DATA_END */"


def main():
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--tokenizer", default=os.path.join(ROOT, "data", "tokenizer.json"),
                    help="tokenizer.json to embed; must be the one the "
                         "checkpoint was trained with")
    ap.add_argument("--header", default=os.path.join(ROOT, "runtime", "bpe.h"))
    args = ap.parse_args()

    with open(args.tokenizer) as f:
        data = json.load(f)
    merges = data["merges"]
    specials = [(piece, SPECIALS[piece]) for piece in SPECIAL_PIECES]

    lines = []
    digest = hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest()[:16]
    lines.append("/* Generated by export_tokenizer.py from %s. */"
                 % os.path.basename(args.tokenizer))
    lines.append("/* BPE_SOURCE_SHA %s */" % digest)
    lines.append("#define BPE_NUM_MERGES %d" % len(merges))
    lines.append("#define BPE_FIRST_MERGE %d" % FIRST_MERGE)
    lines.append("#define BPE_VOCAB_SIZE %d" % (FIRST_MERGE + len(merges)))
    lines.append("#define BPE_NUM_SPECIALS %d" % len(specials))
    lines.append("")
    lines.append("#ifdef BPE_DATA_IMPL")
    lines.append("const uint16_t bpe_merges[BPE_NUM_MERGES][2] = {")
    for i in range(0, len(merges), 8):
        row = ", ".join("{%d,%d}" % (a, b) for a, b in merges[i:i + 8])
        lines.append("    " + row + ",")
    lines.append("};")
    lines.append("const char *const bpe_specials[BPE_NUM_SPECIALS] = {")
    lines.append("    " + ", ".join('"%s"' % piece for piece, _ in specials) + ",")
    lines.append("};")
    lines.append("const uint16_t bpe_special_ids[BPE_NUM_SPECIALS] = {")
    lines.append("    " + ", ".join(str(idx) for _, idx in specials) + ",")
    lines.append("};")
    lines.append("#else")
    lines.append("extern const uint16_t bpe_merges[BPE_NUM_MERGES][2];")
    lines.append("extern const char *const bpe_specials[BPE_NUM_SPECIALS];")
    lines.append("extern const uint16_t bpe_special_ids[BPE_NUM_SPECIALS];")
    lines.append("#endif")
    block = "\n".join(lines)

    path = args.header
    with open(path) as f:
        content = f.read()
    b = content.index(BEGIN)
    e = content.index(END, b)
    if e < b:
        raise ValueError("bpe.h data markers out of order")
    content = content[:b] + "/* BPE_DATA_BEGIN */\n" + block + "\n" + content[e:]
    with open(path, "w") as f:
        f.write(content)
    print("wrote %d data bytes (%d merges, %d specials, FIRST_MERGE=%d, sha %s) "
          "from %s into %s"
          % (len(block), len(merges), len(specials), FIRST_MERGE, digest,
             os.path.basename(args.tokenizer), path))


if __name__ == "__main__":
    main()
