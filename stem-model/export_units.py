"""Export the units the phrasing bank states for each relation argument.

The slot prompts say what an argument wants. `reltable.h` gives its name and
`steptable.h` gives the formula, but neither says whether the number is newtons
or moles, and the only other place a unit appears is inside a solver's printf
where the screen cannot reach it.

`surface.TEMPLATES` states a unit after the placeholder in most phrasings
("{N} N", "{t} s", "{theta} degrees"). This exporter reads that bank — it does
not edit it — and writes the unit each argument is stated with.

Three rules it enforces rather than documents:

  - a unit is kept only when a *majority* of a relation's phrasings state it, so
    the one money-worded percent_change phrasing cannot label its input
    "dollars" when the relation is about percentages;
  - an argument the bank never gives a unit stays "-", which is the truth for a
    coefficient, an index and a ratio, and is why the prompt shows nothing for
    `average_rate_of_change`'s `fa`;
  - nothing is guessed from the symbol. `a` is a coefficient in one relation and
    an acceleration in another, so an unstated unit is left unstated rather than
    filled in from a hand-written table that would be wrong somewhere.

`--check` re-renders and compares, which is what `gate.sh` runs: a generated
artifact no gate checks is how this repository shipped a stale tokenizer.
"""

import argparse
import collections
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)

from relations import RELATIONS  # noqa: E402
from surface import TEMPLATES  # noqa: E402

OUT = os.path.join(ROOT, "runtime", "unitstable.h")

# The units the bank is allowed to state, symbol or word, mapped to the short
# form the prompt shows. A token the bank writes that is not here is not a unit
# as far as this exporter is concerned, which keeps a stray word out of a prompt.
SYMBOLS = """
N J W V A K C mol L M m s kg g cm mm km nm eV Pa Hz F T Wb rad degrees percent %
m/s m/s^2 m/s2 m^3 m^2 cm^3 cm^2 N/m N*m J/kg J/(kg*K) kJ kJ/mol mol/L atm W/m^2
V/m N/C kg/m^3 ohm litre liters litres mL h min years days dollars
""".split()

WORDS = {
    "newtons": "N", "joules": "J", "seconds": "s", "metres": "m",
    "meters": "m", "kilograms": "kg", "grams": "g", "kelvin": "K",
    "volts": "V", "amperes": "A", "amps": "A", "ohms": "ohm", "moles": "mol",
    "litres": "L", "liters": "L", "degrees": "degrees", "percent": "%",
    "dollars": "dollars", "hours": "h", "minutes": "min", "years": "years",
    "atmospheres": "atm", "hertz": "Hz", "watts": "W", "pascals": "Pa",
    "coulombs": "C", "radians": "rad",
}

UNITS = {s: s for s in SYMBOLS}
UNITS.update(WORDS)

# The token right after a placeholder, up to whatever punctuation ends it. A
# unit never contains a space, so one token is the whole unit.
def after(param):
    return re.compile(r"\{" + re.escape(param) + r"\}\s*([^\s.,;:)]+)")


def units_for(name):
    """One entry per argument: the unit a majority of phrasings state, or "-"."""

    params = RELATIONS[name].params
    templates = TEMPLATES.get(name, [])
    need = (len(templates) + 1) // 2
    out = []
    for param in params:
        seen = collections.Counter()
        for template in templates:
            for token in after(param).findall(template):
                if token in UNITS:
                    seen[UNITS[token]] += 1
        best = seen.most_common(1)
        out.append(best[0][0] if best and best[0][1] >= need else "-")
    return out


def rows():
    """(name, units) per relation that states a unit for at least one argument.

    Sorted by name, like every other generated table here, so a diff shows the
    relations that changed rather than a reshuffled block.
    """

    out = []
    for name in sorted(RELATIONS):
        units = units_for(name)
        if any(u != "-" for u in units):
            out.append((name, " ".join(units)))
    return out


def source_sha(rows):
    return hashlib.sha256(json.dumps(rows).encode()).hexdigest()[:16]


def render(rows):
    lines = [
        "/*",
        " * Generated by export_units.py from the phrasing bank. Do not edit by",
        " * hand: the units are what a majority of that relation's phrasings",
        " * state, so a hand-edited row is a claim no phrasing supports.",
        " *",
        " * UNIT_SOURCE_SHA %s" % source_sha(rows),
        " */",
        "#ifndef UNITSTABLE_H",
        "#define UNITSTABLE_H",
        "",
        "#define UNIT_NUM_ROWS %d" % len(rows),
        "",
        "typedef struct {",
        "\tconst char *name;",
        "\t/* One token per argument, in the relation table's order. \"-\" means",
        "\t * the phrasing bank states no unit for that argument. */",
        "\tconst char *units;",
        "} unit_row_t;",
        "",
        "#ifdef UNITSTABLE_IMPL",
        "const unit_row_t unit_rows[UNIT_NUM_ROWS] = {",
    ]
    for name, units in rows:
        lines.append('\t{"%s", "%s"},' % (name, units))
    lines += [
        "};",
        "#else",
        "extern const unit_row_t unit_rows[UNIT_NUM_ROWS];",
        "#endif",
        "",
        "#endif",
    ]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--check", action="store_true",
                    help="fail if the committed header is stale")
    args = ap.parse_args()

    text = render(rows())
    if args.check:
        if not os.path.exists(args.out):
            raise SystemExit(f"{args.out} is missing; run export_units.py")
        if open(args.out, encoding="utf-8").read() != text:
            raise SystemExit(f"{args.out} is stale; run export_units.py")
        print(f"ok: {args.out} matches the phrasing bank")
        return 0

    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    stated = sum(1 for _, u in rows() for t in u.split() if t != "-")
    print(f"wrote units for {stated} arguments of {len(rows())} relations"
          f" into {os.path.relpath(args.out, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
