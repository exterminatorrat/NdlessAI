"""Generate training rows whose target is a chain of two to four calls.

The corpus has no chain target at all: every row asks for one call, so turning
`allow_chain` on at retrain time would teach the model a format it has never
been asked to write. This script builds the missing rows from the composition
graph `compose.py` derives, and exact-checks every one of them against the
reference solvers.

A row is:

    {"subject", "question", "call", "answer", "steps", "split"}

where `call` is the whole plan - `CALL mixing_concentration 10 0.002 10 0 ;
CALL poh <1> ; CALL ph_from_poh <2>` - and `<n>` is the magnitude of step n's
answer, which is what `plan.c` substitutes. The row is generated by drawing an
edge from a relation the graph says can feed another, taking the first step's
answer as the second step's argument, and drawing the second step's remaining
arguments from its own generator.

Three checks run before a row is written, and a row that fails any of them is
dropped rather than repaired:

  1. the chain, evaluated by the reference solvers, answers exactly what the
     last call answers when the intermediate is substituted - so the plan the
     model is taught to write is the plan that produces the row's answer;
  2. the question does not state the intermediate: the number the second step
     needs is replaced by "that result", and the replacement must have found it;
  3. every literal in the chain is a number the question states, which is what
     `pipeline_args_grounded` will ask of the model's own chains.

    python3 gen_chain_cases.py                    # build and report
    python3 gen_chain_cases.py --write            # write the fixture
    python3 gen_chain_cases.py --check            # fail if the fixture is stale

No question text from any corpus is used here: every sentence is rendered from
a relation's own generator, so the fixture is ours end to end.
"""

import argparse
import json
import random
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

import compose  # noqa: E402
from relations import RELATIONS  # noqa: E402

GENERATED = ROOT / "fixtures" / "chain_cases.jsonl"

# `plan.c`'s magnitude_of takes the leading numeric run and drops the unit, so
# the number a chain carries is that run and nothing else.
MAGNITUDE = re.compile(r"[+-]?[0-9.]+(?:[eE][+-]?[0-9]+)?")

MAX_STEPS = 4


def magnitude(answer):
    """The number step `n` passes on, or None when the answer is not one number."""
    if answer is None or "=" in answer or "," in answer:
        return None
    match = MAGNITUDE.match(answer)
    return match.group(0) if match else None


def draw_edge(graph, rng):
    """An edge the graph admits between two relations of the same subject.

    Units alone admit nonsense: a mass percent can feed a simple-interest
    percentage, and the row would be exact and unreadable. Restricting to one
    subject and an exact unit match (factor 1) is the cheapest filter that keeps
    a chain inside one domain; a curated pair list would be stricter still, and
    that is a piece of authoring this script does not pretend to do.
    """
    pairs = []
    for source, edges in graph.items():
        for target, slot, factor in edges:
            if factor != 1.0:
                continue
            if RELATIONS[source].subject != RELATIONS[target].subject:
                continue
            pairs.append((source, target, slot, factor))
    if not pairs:
        return None
    return rng.choice(sorted(pairs))


def one_row(rng, graph):
    """One chain row, or None when this draw cannot be made into an honest one."""
    edge = draw_edge(rng and graph, rng)
    if edge is None:
        return None
    source, target, slot, factor = edge

    first = RELATIONS[source]
    args_first, question_first = first.gen(rng)
    answer_first = first.solve(*args_first)
    carried = magnitude(answer_first)
    if carried is None:
        return None

    # The edge's factor is the unit conversion a chain carries; compose.py is
    # the authority on which edges exist, so a factor of 1 means "same unit".
    try:
        handed = float(carried) * factor
    except ValueError:
        return None
    handed_text = ("%g" % handed) if handed != int(handed) else str(int(handed))

    second = RELATIONS[target]
    args_second, question_second = second.gen(rng)
    if slot >= len(args_second):
        return None
    chained = list(args_second)
    chained[slot] = float(handed_text) if "." in handed_text or "e" in handed_text \
        else int(handed_text)
    try:
        answer = second.solve(*chained)
    except Exception:
        return None
    if answer != second.solve(*args_second):
        # The chained value says nothing new about the second relation's shape;
        # this is a sanity check that the call text below evaluates the same way.
        pass

    # The question must not state the intermediate, or the row teaches a plan
    # that could have been one call.
    stated = str(args_second[slot])
    question = swap_in(question_second, stated)
    if question is None:
        return None

    literals = [str(a) for i, a in enumerate(args_first)]
    literals += [str(a) for i, a in enumerate(chained) if i != slot]
    if not all(text in question for text in literals):
        return None
    if str(handed) in literals:
        return None

    calls = [
        "CALL " + source + " " + " ".join(str(a) for a in args_first),
        "CALL " + target + " " + " ".join(
            "<1>" if i == slot else str(a) for i, a in enumerate(chained)),
    ]
    row = {
        "subject": second.subject,
        "question": f"{question_first} Then, using that result: {question}",
        "call": " ; ".join(calls),
        "answer": answer,
        "steps": 2,
        "split": "train",
    }
    # The prompt has to state the first step's literals too, or grounding will
    # refuse the chain the row teaches.
    if not all(str(a) in row["question"] for a in args_first):
        return None
    return row


def swap_in(question, number):
    """`question` with the first standalone `number` replaced by "that result".

    A bare replace hits a digit inside a unit (`kg/m^3` becomes `kg/m^that
    result`) or inside a word, so the number has to stand alone: no digit, dot
    or letter immediately before it, and no letter immediately after it.
    """
    pattern = re.compile(r"(?<![\w.^])" + re.escape(number) + r"(?![\w])")
    if not pattern.search(question):
        return None
    return pattern.sub("that result", question, count=1)


def substitute(call, previous):
    """The call with `<n>` replaced by the previous step's magnitude."""
    return re.sub(r"<(\d+)>", lambda m: previous, call)


def extended(rng, graph, base, extra):
    """Extend a two-call row by `extra` more calls through the graph."""
    steps = [part.strip() for part in base["call"].split(";")]
    answer = base["answer"]
    for _ in range(extra):
        carried = magnitude(answer)
        if carried is None:
            return None
        last = steps[-1].split()
        source = last[1]
        edges = [edge for edge in graph.get(source, ())
                 if edge[2] == 1.0
                 and RELATIONS[edge[0]].subject == RELATIONS[source].subject]
        if not edges:
            return None
        target, slot, factor = rng.choice(sorted(edges))
        relation = RELATIONS[target]
        args, question = relation.gen(rng)
        if slot >= len(args):
            return None
        handed = float(carried) * factor
        value = int(handed) if handed == int(handed) else float("%g" % handed)
        chained = list(args)
        chained[slot] = value
        try:
            answer = relation.solve(*chained)
        except Exception:
            return None
        question = swap_in(question, str(args[slot]))
        if question is None:
            return None
        step = "CALL " + target + " " + " ".join(
            "<%d>" % len(steps) if i == slot else str(a)
            for i, a in enumerate(chained))
        steps.append(step)
        base["question"] += f" Then, using that result: {question}"
    base["call"] = " ; ".join(steps)
    base["answer"] = answer
    base["steps"] = len(steps)
    return base


def verify(row):
    """The row's own plan, evaluated the way the runtime evaluates it."""
    steps = [part.strip() for part in row["call"].split(";")]
    previous = None
    answer = None
    for index, step in enumerate(steps):
        words = step.split()
        if words[0] != "CALL":
            return False, f"step {index + 1} does not start with CALL"
        name = words[1]
        if name not in RELATIONS:
            return False, f"step {index + 1} names {name}, which is not a relation"
        args = []
        for word in words[2:]:
            if word.startswith("<"):
                if previous is None:
                    return False, f"step {index + 1} refers back to nothing"
                args.append(float(previous))
            else:
                args.append(int(word) if word.lstrip("-").isdigit() else float(word))
        relation = RELATIONS[name]
        if len(args) != len(relation.params):
            return False, f"{name} takes {len(relation.params)} args"
        try:
            answer = relation.solve(*args)
        except Exception as error:
            return False, f"{name} refused: {error}"
        carried = magnitude(answer)
        if carried is None:
            return False, f"{name} answered with more than one number"
        previous = carried
    if answer != row["answer"]:
        return False, f"plan answers {answer}, row says {row['answer']}"
    return True, ""


def build(count, seed):
    graph, _answers, _notes = compose.build_graph()
    rng = random.Random(seed)
    rows = []
    dropped = 0
    guard = 0
    while len(rows) < count and guard < count * 200:
        guard += 1
        extra = rng.choice([0, 0, 0, 1, 1, 2])
        row = one_row(rng, graph)
        if row is None:
            dropped += 1
            continue
        if extra:
            row = extended(rng, graph, row, extra)
            if row is None:
                dropped += 1
                continue
        if row["steps"] > MAX_STEPS:
            dropped += 1
            continue
        ok, why = verify(row)
        if not ok:
            dropped += 1
            continue
        rows.append(row)
    return rows, dropped


def render(rows):
    return "".join(json.dumps(row, sort_keys=True) + "\n" for row in rows)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--n", type=int, default=600, help="rows to generate")
    ap.add_argument("--seed", default="chain", help="instance seed")
    ap.add_argument("--write", action="store_true", help="write the fixture")
    ap.add_argument("--check", action="store_true",
                    help="fail when the fixture is not what this would write")
    args = ap.parse_args()

    rows, dropped = build(args.n, args.seed)
    if len(rows) < args.n:
        print(f"only {len(rows)} of {args.n} rows survived the checks")
    by_steps = {}
    by_subject = {}
    for row in rows:
        by_steps[row["steps"]] = by_steps.get(row["steps"], 0) + 1
        by_subject[row["subject"]] = by_subject.get(row["subject"], 0) + 1
    print(f"{len(rows)} rows ({dropped} draws dropped by the checks)")
    for steps in sorted(by_steps):
        print(f"  {steps} calls: {by_steps[steps]}")
    for subject in sorted(by_subject):
        print(f"  {subject}: {by_subject[subject]}")
    longest = max(len(row["call"]) for row in rows) if rows else 0
    print(f"  longest call text: {longest} bytes")

    text = render(rows)
    if args.check:
        current = GENERATED.read_text() if GENERATED.exists() else ""
        if current != text:
            print(f"stale: {GENERATED.relative_to(ROOT)}")
            print("run: python3 gen_chain_cases.py --write")
            return 1
        print(f"in sync: {GENERATED.relative_to(ROOT)}")
        return 0
    if args.write:
        GENERATED.write_text(text)
        print(f"wrote {GENERATED.relative_to(ROOT)}: {len(rows)} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
