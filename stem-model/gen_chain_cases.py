"""Generate training rows whose target is a chain of two to four calls.

The corpus has no chain target at all: every row asks for one call, so turning
`allow_chain` on at retrain time would teach the model a format it has never
been asked to write. This script builds the missing rows from the composition
graph `compose.py` derives, and exact-checks every one of them against the
reference solvers.

A row is:

    {"subject", "question", "call", "answer", "steps", "split"}

where `call` is the whole plan - `CALL mixing_concentration 10 0.002 10 0 ;
CALL poh <1> ; CALL ph_from_poh <2>` - and `<n>` is the magnitude of step n's
answer, which is what `plan.c` substitutes. The row is generated by drawing an
edge from a relation the graph says can feed another, taking the first step's
answer as the second step's argument, and drawing the second step's remaining
arguments from its own generator.

Three checks run before a row is written, and a row that fails any of them is
dropped rather than repaired:

  1. the chain, evaluated by the reference solvers, answers exactly what the
     last call answers when the intermediate is substituted - so the plan the
     model is taught to write is the plan that produces the row's answer;
  2. the question does not state the intermediate: the number the second step
     needs is replaced by "that result", and the replacement must have found it;
  3. every literal in the chain is a number the question states, which is what
     `pipeline_args_grounded` will ask of the model's own chains.

    python3 gen_chain_cases.py                    # build and report
    python3 gen_chain_cases.py --write            # write the fixture
    python3 gen_chain_cases.py --check            # fail if the fixture is stale

No question text from any corpus is used here: every sentence is rendered from
a relation's own generator, so the fixture is ours end to end.
"""

import argparse
import json
import random
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

import compose  # noqa: E402
from relations import RELATIONS  # noqa: E402
from surface.spec import SPECS  # noqa: E402

GENERATED = ROOT / "fixtures" / "chain_cases.jsonl"

# `plan.c`'s magnitude_of takes the leading numeric run and drops the unit, so
# the number a chain carries is that run and nothing else.
MAGNITUDE = re.compile(r"[+-]?[0-9.]+(?:[eE][+-]?[0-9]+)?")

MAX_STEPS = 4

# train.pack() skips a row longer than seq + 1 with the reading window at 192,
# and a skipped row is never trained on. A row has to fit to exist.
PACK_LIMIT = 193


def magnitude(answer):
    """The number step `n` passes on, or None when the answer is not one number."""
    if answer is None or "=" in answer or "," in answer:
        return None
    match = MAGNITUDE.match(answer)
    return match.group(0) if match else None


def draw_edge(graph, rng):
    """An edge the graph admits between two relations of the same subject.

    Units alone admit nonsense: a mass percent can feed a simple-interest
    percentage, and the row would be exact and unreadable. Restricting to one
    subject and an exact unit match (factor 1) is the cheapest filter that keeps
    a chain inside one domain; a curated pair list would be stricter still, and
    that is a piece of authoring this script does not pretend to do.
    """
    pairs = []
    for source, edges in graph.items():
        for target, slot, factor in edges:
            if factor != 1.0:
                continue
            if RELATIONS[source].subject != RELATIONS[target].subject:
                continue
            pairs.append((source, target, slot, factor))
    if not pairs:
        return None
    return rng.choice(sorted(pairs))


def one_row(rng, graph):
    """One chain row, or None when this draw cannot be made into an honest one."""
    edge = draw_edge(rng and graph, rng)
    if edge is None:
        return None
    source, target, slot, factor = edge

    first = RELATIONS[source]
    args_first, question_first = first.gen(rng)
    answer_first = first.solve(*args_first)
    carried = magnitude(answer_first)
    if carried is None:
        return None

    # The edge's factor is the unit conversion a chain carries; compose.py is
    # the authority on which edges exist, so a factor of 1 means "same unit".
    try:
        handed = float(carried) * factor
    except ValueError:
        return None
    handed_text = ("%g" % handed) if handed != int(handed) else str(int(handed))

    second = RELATIONS[target]
    args_second, question_second = second.gen(rng)
    if slot >= len(args_second):
        return None
    chained = list(args_second)
    chained[slot] = float(handed_text) if "." in handed_text or "e" in handed_text \
        else int(handed_text)
    try:
        answer = second.solve(*chained)
    except Exception:
        return None
    if answer != second.solve(*args_second):
        # The chained value says nothing new about the second relation's shape;
        # this is a sanity check that the call text below evaluates the same way.
        pass

    # The question must not state the intermediate, or the row teaches a plan
    # that could have been one call.
    stated = str(args_second[slot])
    question = swap_in(question_second, stated)
    if question is None:
        return None

    literals = [str(a) for i, a in enumerate(args_first)]
    literals += [str(a) for i, a in enumerate(chained) if i != slot]
    if not all(text in question for text in literals):
        return None
    if str(handed) in literals:
        return None

    calls = [
        "CALL " + source + " " + " ".join(str(a) for a in args_first),
        "CALL " + target + " " + " ".join(
            "<1>" if i == slot else str(a) for i, a in enumerate(chained)),
    ]
    # One statement, one ask: a multi-step exam question states its givens once
    # rather than concatenating two questions. The first step's numbers travel as
    # a "With ..." clause in the catalogue's own slot wording, and the second
    # step's own question keeps the ask and its own givens.
    steps = [[source, list(args_first), None],
             [target, [None if i == slot else a for i, a in enumerate(chained)], slot]]
    question = assemble(steps, question)
    if question is None:
        return None
    row = {
        "subject": second.subject,
        "question": question,
        "last_question": question,
        "call": " ; ".join(calls),
        "answer": answer,
        "steps": 2,
        "split": "train",
    }
    # The prompt has to state the first step's literals too, or grounding will
    # refuse the chain the row teaches.
    if not all(str(a) in row["question"] for a in args_first):
        return None
    return row


def claim(relation, values):
    """One step's literals as a clause a single-statement question can carry.

    "14.2 g as the mass of the sample, 284 g/mol as the molar mass". The role
    and the unit come from the relation's own spec, so a chain prompt states its
    givens the way the catalogue already phrases them; a relation with no spec
    falls back to its parameter name, which is still a word rather than a blank.
    """
    described = SPECS.get(relation)
    if described is None:
        return None
    parts = []
    for index, (param, value) in enumerate(zip(RELATIONS[relation].params, values)):
        if value is None:
            continue
        slot = described.slots[param] if described and param in described.slots else None
        role = slot.role if slot else param.replace("_", " ")
        unit = slot.unit if slot else ""
        parts.append(f"{value} {unit} as the {role}".replace("  ", " "))
    return ", ".join(parts)


def swap_in(question, number):
    """`question` with the first standalone `number` replaced by "that result".

    A bare replace hits a digit inside a unit (`kg/m^3` becomes `kg/m^that
    result`) or inside a word, so the number has to stand alone: no digit, dot
    or letter immediately before it, and no letter immediately after it.
    """
    pattern = re.compile(r"(?<![\w.^])" + re.escape(number) + r"(?![\w])")
    if not pattern.search(question):
        return None
    return pattern.sub("that result", question, count=1)


def substitute(call, previous):
    """The call with `<n>` replaced by the previous step's magnitude."""
    return re.sub(r"<(\d+)>", lambda m: previous, call)


def parse_steps(call):
    """[(relation, args, chained index)] from a call text, refs as None."""
    steps = []
    for part in call.split(";"):
        words = part.split()
        args, chained = [], None
        for index, word in enumerate(words[2:]):
            if word.startswith("<"):
                chained = index
                args.append(None)
            else:
                args.append(int(word) if word.lstrip("-").isdigit() else float(word))
        steps.append([words[1], args, chained])
    return steps


def render_steps(steps):
    out = []
    for index, (name, args, chained) in enumerate(steps):
        words = ["CALL", name]
        for position, value in enumerate(args):
            words.append("<%d>" % index if position == chained else str(value))
        out.append(" ".join(words))
    return " ; ".join(out)


def assemble(steps, last_question):
    """One statement: the earlier steps' givens as a clause, then the ask.

    A multi-step exam question states its givens once. The clause carries only
    the literals of the steps that are no longer last - the last step's own
    question already states its own - so nothing is said twice.
    """
    clauses = [claim(name, args) for name, args, _ in steps[:-1]]
    if not clauses or None in clauses:
        return None
    lowered = last_question[0].lower() + last_question[1:]
    return f"With {'; '.join(clauses)}, {lowered}"


def extended(rng, graph, base, extra):
    """Extend a two-call row by `extra` more calls through the graph."""
    steps = parse_steps(base["call"])
    answer = base["answer"]
    last_question = base["last_question"]
    for _ in range(extra):
        carried = magnitude(answer)
        if carried is None:
            return None
        source = steps[-1][0]
        edges = [edge for edge in graph.get(source, ())
                 if edge[2] == 1.0
                 and RELATIONS[edge[0]].subject == RELATIONS[source].subject]
        if not edges:
            return None
        target, slot, factor = rng.choice(sorted(edges))
        relation = RELATIONS[target]
        args, question = relation.gen(rng)
        if slot >= len(args):
            return None
        handed = float(carried) * factor
        value = int(handed) if handed == int(handed) else float("%g" % handed)
        chained = list(args)
        chained[slot] = value
        try:
            answer = relation.solve(*chained)
        except Exception:
            return None
        last_question = swap_in(question, str(args[slot]))
        if last_question is None:
            return None
        steps.append([target, [None if i == slot else a for i, a in enumerate(chained)], slot])
    question = assemble(steps, last_question)
    if question is None:
        return None
    base["call"] = render_steps(steps)
    base["question"] = question
    base["answer"] = answer
    base["steps"] = len(steps)
    base.pop("last_question", None)
    return base


def verify(row):
    """The row's own plan, evaluated the way the runtime evaluates it."""
    steps = [part.strip() for part in row["call"].split(";")]
    previous = None
    answer = None
    for index, step in enumerate(steps):
        words = step.split()
        if words[0] != "CALL":
            return False, f"step {index + 1} does not start with CALL"
        name = words[1]
        if name not in RELATIONS:
            return False, f"step {index + 1} names {name}, which is not a relation"
        args = []
        for word in words[2:]:
            if word.startswith("<"):
                if previous is None:
                    return False, f"step {index + 1} refers back to nothing"
                args.append(float(previous))
            else:
                args.append(int(word) if word.lstrip("-").isdigit() else float(word))
        relation = RELATIONS[name]
        if len(args) != len(relation.params):
            return False, f"{name} takes {len(relation.params)} args"
        try:
            answer = relation.solve(*args)
        except Exception as error:
            return False, f"{name} refused: {error}"
        carried = magnitude(answer)
        if carried is None:
            return False, f"{name} answered with more than one number"
        previous = carried
    if answer != row["answer"]:
        return False, f"plan answers {answer}, row says {row['answer']}"
    return True, ""


BPE_HEADER = ROOT / "runtime" / "bpe.h"


def token_table():
    """The shipped tokenizer, read from the generated header.

    `data/tokenizer.json` is what a retrain writes; until then `bpe.h` is the
    only table that exists, and it is the one the device runs. Reading it means a
    chain row's length is measured against the tokenizer that will see it.
    """
    text = BPE_HEADER.read_text(encoding="utf-8")
    first = int(re.search(r"#define BPE_FIRST_MERGE (\d+)", text).group(1))
    merges_text = re.search(r"bpe_merges\[BPE_NUM_MERGES\]\[2\] = \{(.*?)\n\};",
                            text, re.S).group(1)
    merges = [(int(a), int(b)) for a, b in re.findall(r"\{(\d+),(\d+)\}", merges_text)]
    specials_text = re.search(r"bpe_specials\[BPE_NUM_SPECIALS\] = \{(.*?)\n\};",
                              text, re.S).group(1)
    names = re.findall(r'"([^"]*)"', specials_text)
    ids_text = re.search(r"bpe_special_ids\[BPE_NUM_SPECIALS\] = \{(.*?)\n\};",
                         text, re.S).group(1)
    ids = [int(value) for value in re.findall(r"\d+", ids_text)]
    return dict(zip(names, ids)), {pair: first + i for i, pair in enumerate(merges)}


def encode(text, specials, ranks):
    """Token ids, the way tokenizer.py does it: specials first, then BPE on bytes."""
    out = []
    keys = sorted(specials, key=len, reverse=True)
    index = 0
    while index < len(text):
        for key in keys:
            if text.startswith(key, index):
                out.append(specials[key])
                index += len(key)
                break
        else:
            start = index
            while index < len(text) and not any(text.startswith(k, index) for k in keys):
                index += 1
            ids = list(text[start:index].encode())
            while len(ids) > 1:
                best = None
                for i in range(len(ids) - 1):
                    rank = ranks.get((ids[i], ids[i + 1]))
                    if rank is not None and (best is None or rank < best[0]):
                        best = (rank, i)
                if best is None:
                    break
                _, at = best
                ids[at:at + 2] = [ranks[(ids[at], ids[at + 1])]]
            out.extend(ids)
    return out


def row_tokens(row, specials, ranks):
    """What `pack()` would count: question, <sep>, call, end token."""
    return (len(encode(row["question"], specials, ranks)) + 1
            + len(encode(row["call"], specials, ranks)) + 1)


def token_report(rows):
    specials, ranks = token_table()
    counts = {}
    for row in rows:
        counts.setdefault(row["steps"], []).append(row_tokens(row, specials, ranks))
    print("tokens per row (question + <sep> + call + end), shipped bpe.h:")
    for steps in sorted(counts):
        values = sorted(counts[steps])
        pick = lambda p: values[min(len(values) - 1, int(round(p * (len(values) - 1))))]
        fits = sum(1 for value in values if value <= PACK_LIMIT)
        print(f"  {steps} calls: n={len(values)} p50={pick(0.5)} p95={pick(0.95)} "
              f"max={values[-1]} fits {PACK_LIMIT}: {fits}/{len(values)}")
    every = sorted(value for group in counts.values() for value in group)
    pick = lambda p: every[min(len(every) - 1, int(round(p * (len(every) - 1))))]
    print(f"  all: n={len(every)} p50={pick(0.5)} p95={pick(0.95)} max={every[-1]}")


def build(count, seed, max_steps=MAX_STEPS):
    graph, _answers, _notes = compose.build_graph()
    specials, ranks = token_table()
    rng = random.Random(seed)
    rows = []
    dropped = 0
    guard = 0
    while len(rows) < count and guard < count * 200:
        guard += 1
        extra = rng.choice([0, 0, 0, 1, 1, 2])
        row = one_row(rng, graph)
        if row is None:
            dropped += 1
            continue
        if extra:
            row = extended(rng, graph, row, extra)
            if row is None:
                dropped += 1
                continue
        if row["steps"] > max_steps:
            dropped += 1
            continue
        ok, why = verify(row)
        if not ok:
            dropped += 1
            continue
        # `train.pack()` skips a row longer than the window rather than cutting
        # it, so a row over the limit is a row the model never sees. Drop it
        # here, where the count is visible, instead of letting a warning line
        # carry it into a training run.
        if row_tokens(row, specials, ranks) > PACK_LIMIT:
            dropped += 1
            continue
        rows.append(row)
    return rows, dropped


def render(rows):
    return "".join(json.dumps(row, sort_keys=True) + "\n" for row in rows)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--n", type=int, default=600, help="rows to generate")
    ap.add_argument("--seed", default="chain", help="instance seed")
    ap.add_argument("--write", action="store_true",
                    help="write the fixture (the shipped corpus is "
                         "`--n 600 --max-steps 2`)")
    ap.add_argument("--check", action="store_true",
                    help="fail when the fixture is not what this would write "
                         "(run with `--n 600 --max-steps 2`)")
    ap.add_argument("--max-steps", type=int, default=MAX_STEPS,
                    help="longest chain to generate (2 keeps every row inside "
                         "pack()'s window)")
    ap.add_argument("--tokens", action="store_true",
                    help="report the token distribution instead of building")
    args = ap.parse_args()

    rows, dropped = build(args.n, args.seed, args.max_steps)
    if args.tokens:
        token_report(rows)
        return 0
    if len(rows) < args.n:
        print(f"only {len(rows)} of {args.n} rows survived the checks")
    by_steps = {}
    by_subject = {}
    for row in rows:
        by_steps[row["steps"]] = by_steps.get(row["steps"], 0) + 1
        by_subject[row["subject"]] = by_subject.get(row["subject"], 0) + 1
    print(f"{len(rows)} rows ({dropped} draws dropped by the checks)")
    for steps in sorted(by_steps):
        print(f"  {steps} calls: {by_steps[steps]}")
    for subject in sorted(by_subject):
        print(f"  {subject}: {by_subject[subject]}")
    longest = max(len(row["call"]) for row in rows) if rows else 0
    print(f"  longest call text: {longest} bytes")

    text = render(rows)
    if args.check:
        current = GENERATED.read_text() if GENERATED.exists() else ""
        if current != text:
            print(f"stale: {GENERATED.relative_to(ROOT)}")
            print("run: python3 gen_chain_cases.py --write")
            return 1
        print(f"in sync: {GENERATED.relative_to(ROOT)}")
        return 0
    if args.write:
        GENERATED.write_text(text)
        print(f"wrote {GENERATED.relative_to(ROOT)}: {len(rows)} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
