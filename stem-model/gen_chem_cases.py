"""Record what the Python reference answers for a set of formulas.

`test_formula.c` replays this file against the C parser, so the two
implementations are compared row by row rather than assumed to agree because
they read the same header. The values come from `chem/formula.py`; a parser
change that moves any of them makes the fixture stale, and `--check` says so.

    python3 gen_chem_cases.py            # rewrite the fixture
    python3 gen_chem_cases.py --check    # exit 1 if the fixture is stale
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)

from chem import elements, formula, variants  # noqa: E402

DEFAULT_FIXTURE = os.path.join(ROOT, "runtime", "fixtures", "chem_cases.txt")
DEFAULT_VARIANTS = os.path.join(ROOT, "runtime", "fixtures", "chem_variants.txt")

FORMULAS = [
    # The formulas a chemistry course actually writes.
    "H2O", "CH3OH", "C2H5OH", "CH4", "C2H6", "C3H8", "C4H10", "C6H6",
    "C6H12O6", "C12H22O11", "H2O2", "CO", "CO2", "SO2", "SO3", "NO", "NO2",
    "N2O4", "N2O5", "NH3", "HNO3", "HNO2", "H2SO4", "H3PO4", "HCl",
    "HBr", "HF", "HCN", "CH3COOH", "C2H5COOH", "HCOOH", "H2C2O4",
    "C3H6O3", "C6H5COOH", "C3H8O3",
    # Salts, including the groups and charges the ion path has to read.
    "NaCl", "KCl", "KBr", "KI", "NaF", "CaF2", "MgO", "CaO", "BaO",
    "NaOH", "KOH", "Mg(OH)2", "Ca(OH)2", "Al(OH)3", "CaCO3", "Na2CO3",
    "K2CO3", "NaHCO3", "Na2SO4", "K2SO4", "MgSO4", "CuSO4", "AgNO3",
    "KNO3", "Fe(NO3)2", "Fe(NO3)3", "Cu(NO3)2", "Pb(NO3)2", "Al(NO3)3",
    "Ba(NO3)2", "NH4Cl", "(NH4)2SO4", "NH4NO3", "KMnO4", "NaC2H3O2",
    "C2H3O2", "Al2(SO4)3", "Cu3(PO4)2", "Na3PO4", "Ca3(PO4)2", "AgCl",
    "PbCl2", "KSCN", "FeSCN", "MgCl2", "CaCl2",
    # Hydrates and unicode the bank writes.
    "CuSO4.5H2O", "Na2CO3.10H2O", "MgSO4.7H2O", "CuSO4\u00b75H2O",
    "H\u2082O", "Ba(NO\u2083)\u2082",
    # Refusals: these must answer nothing in both languages.
    "H2X", "Xx2", "Ca(OH2", "CaOH)2", "H0", "2H2O", "NaCl(", "",
    "propanol", "unobtainium", "Na2O2", "NaCl2", "ClF3", "Na", "Cs2S2O3",
    "Ba2+", "Ba(NO3)2 2+",
]

NAMES = sorted(elements.NAMES)

# (name, arguments). The answers come from chem/variants.py; a row whose
# answer is "-" is a call the reference refuses, which the C solver must refuse
# too.
VARIANT_CASES = [
    ("molar_mass_formula", ["CH3OH"]),
    ("molar_mass_formula", ["methanol"]),
    ("molar_mass_formula", ["CuSO4.5H2O"]),
    ("molar_mass_formula", ["H2X"]),
    ("moles_from_mass_formula", ["128", "CH3OH"]),
    ("moles_from_mass_formula", ["128", "methanol"]),
    ("moles_from_mass_formula", ["36", "water"]),
    ("moles_from_mass_formula", ["128", "propanol"]),
    ("mass_from_moles_formula", ["2", "CH3OH"]),
    ("mass_from_moles_formula", ["0.5", "CaCO3"]),
    ("mass_from_moles_formula", ["abc", "CH3OH"]),
    ("ions_from_moles_formula", ["0.2", "Ba(NO3)2"]),
    ("ions_from_moles_formula", ["0.1", "MgCl2"]),
    ("ions_from_moles_formula", ["0.2", "CH4"]),
    ("ksp_from_solubility_formula", ["0.01", "Ca(OH)2"]),
    ("ksp_from_solubility_formula", ["0.001", "AgCl"]),
    ("ksp_from_solubility_formula", ["0.002", "Al2(SO4)3"]),
    ("ksp_from_solubility_formula", ["0.01", "CO2"]),
    ("mole_fraction_formula", ["128", "CH3OH", "108", "H2O"]),
    ("mole_fraction_formula", ["18", "H2O", "18", "CH4"]),
    ("mole_fraction_formula", ["128", "CH3OH", "108", "H2X"]),
    ("stoich_mass_formula", ["12", "Al", "2", "AlCl3"]),
    ("stoich_mass_formula", ["8", "N2H4", "1", "N2"]),
    ("stoich_mass_formula", ["8", "N2H4", "1", "H2O"]),
]


def rows():
    out = []
    for text in FORMULAS + NAMES:
        out.append(text)
    seen = []
    for text in out:
        try:
            mg = "%d" % formula.molar_mass_mg(text)
        except formula.FormulaError:
            mg = "-"
        try:
            cations, anions = formula.ion_counts(text)
            ions = "%d\t%d" % (cations, anions)
        except formula.FormulaError:
            ions = "-\t-"
        seen.append("%s\t%s\t%s" % (text, mg, ions))
    return seen


def variant_rows():
    out = []
    for name, args in VARIANT_CASES:
        try:
            answer = variants.solve(name, args)
        except formula.FormulaError:
            answer = "-"
        out.append("%s\t%s\t%s" % (name, ";".join(args), answer))
    return out


def render_variants(rows):
    lines = [
        "# Generated by gen_chem_cases.py from chem/variants.py. Do not edit by",
        "# hand: test_formula.c replays these rows against the C solvers.",
    ]
    lines += rows
    return "\n".join(lines) + "\n"


def render(seen):
    lines = [
        "# Generated by gen_chem_cases.py from chem/formula.py. Do not edit by",
        "# hand: test_formula.c replays these rows against the C parser.",
    ]
    for row in seen:
        lines.append(row)
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fixture", default=DEFAULT_FIXTURE)
    ap.add_argument("--variants", default=DEFAULT_VARIANTS)
    ap.add_argument("--check", action="store_true",
                    help="fail if the fixture is stale instead of rewriting it")
    args = ap.parse_args()

    want = render(rows())
    want_variants = render_variants(variant_rows())
    if args.check:
        for path, want_text, source in (
                (args.fixture, want, "chem/formula.py"),
                (args.variants, want_variants, "chem/variants.py")):
            if not os.path.exists(path):
                print("STALE: %s does not exist" % path)
                print("Run: python3 gen_chem_cases.py")
                return 1
            with open(path) as f:
                got = f.read()
            if got != want_text:
                print("STALE: %s does not match %s" % (path, source))
                print("Run: python3 gen_chem_cases.py")
                return 1
        print("ok: chem cases match chem/formula.py and chem/variants.py")
        return 0

    for path, text, source in ((args.fixture, want, "chem/formula.py"),
                               (args.variants, want_variants, "chem/variants.py")):
        if os.path.exists(path):
            with open(path) as f:
                if f.read() == text:
                    print("%s already matches %s; not rewritten" % (path, source))
                    continue
        with open(path, "w") as f:
            f.write(text)
        print("wrote %s from %s" % (path, source))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
