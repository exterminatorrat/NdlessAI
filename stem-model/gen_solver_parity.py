"""Cross-check every relation in relations/ against the C solver table.

The Python relations are the catalogue the model is trained on; the C solvers
in runtime/ are what the calculator actually runs, and nothing connected the
two. A relation the model can emit but the runtime answers differently, or not
at all, is a wrong answer the student cannot avoid. So this script draws fixed,
seeded instances per relation, records what solve() returns for each, and
compares it against the runtime's answer for the same call.

    python3 gen_solver_parity.py             # gaps, regenerate, build, run
    python3 gen_solver_parity.py --n 400     # deeper soak
    python3 gen_solver_parity.py --write-only

The artefact is runtime/test_parity.c, a generated case table built by the
runtime Makefile target `test_parity`. The first thing printed is the two gap
lists: relations with no C solver, and C solvers with no registered relation.
A gap or a mismatch exits 1.
"""

import argparse
import random
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RUNTIME = ROOT / "runtime"
sys.path.insert(0, str(ROOT))

from relations import RELATIONS  # noqa: E402

GENERATED = RUNTIME / "test_parity.c"

# Every subject solver recognises a relation by comparing the name against a
# string literal. Reading those literals is the only way to see the runtime's
# own catalogue without a second generated list that could drift from it.
C_NAME = re.compile(r'strcmp\(name, "([a-z0-9_]+)"\)')

# A relation's rows travel as one string literal, so the C side copies it into
# a fixed buffer; keep the fixture inside that buffer.
MAX_ROWS = 16000

TEMPLATE = r"""/*
 * Generated by gen_solver_parity.py; do not edit.
 *
 * One row per instance drawn from the Python relation: the call arguments as
 * the model emits them, then the answer solve() gave. The runtime has to
 * reproduce every answer byte for byte, or the calculator disagrees with the
 * catalogue the model was trained on. Regenerate with:
 *   python3 gen_solver_parity.py
 */
#include <stdio.h>
#include <string.h>

#include "solvers.h"

typedef struct {
	const char *name;
	const char *rows;
} parity_rel;

static const parity_rel RELS[] = {
__ROWS__
};

static int run_rel(const parity_rel *r, int *cases)
{
	char buf[16384], want[160], got[160], argbuf[128], *save = NULL;
	char *field;
	int n = 0, bad = 0;

	if (strlen(r->rows) >= sizeof(buf)) {
		printf("%s: rows string too long\n", r->name);
		return 1;
	}
	memcpy(buf, r->rows, strlen(r->rows) + 1);
	for (field = strtok_r(buf, "|", &save); field != NULL;
	     field = strtok_r(NULL, "|", &save)) {
		const char *argv[6];
		char *asave = NULL, *tok, *answer;
		int na = 0, rc;

		answer = strtok_r(NULL, "|", &save);
		if (answer == NULL) {
			printf("%s: rows do not pair up\n", r->name);
			return 1;
		}
		if (strlen(field) >= sizeof(argbuf) ||
		    strlen(answer) >= sizeof(want)) {
			printf("%s: a case is longer than the fixture buffer\n",
			       r->name);
			return 1;
		}
		memcpy(argbuf, field, strlen(field) + 1);
		for (tok = strtok_r(argbuf, " ", &asave);
		     tok != NULL && na < 6;
		     tok = strtok_r(NULL, " ", &asave))
			argv[na++] = tok;
		snprintf(want, sizeof(want), "%s", answer);
		rc = solvers_solve(r->name, argv, na, got, sizeof(got));
		n++;
		if (rc != 0 || strcmp(got, want) != 0) {
			if (bad < 5)
				fprintf(stderr,
				        "FAIL %s %s rc=%d got='%s' want='%s'\n",
				        r->name, field, rc, got, want);
			bad++;
		}
	}
	*cases += n;
	printf("%-18s %4d cases, %d mismatches\n", r->name, n, bad);
	return bad;
}

int main(void)
{
	unsigned i;
	int cases = 0, bad = 0;

	for (i = 0; i < sizeof(RELS) / sizeof(RELS[0]); i++)
		bad += run_rel(&RELS[i], &cases);
	printf("TOTAL %d cases, %d mismatches\n", cases, bad);
	return bad == 0 ? 0 : 1;
}
"""


def c_solver_names():
    names = set()
    for path in sorted(RUNTIME.glob("solvers_*.c")):
        names.update(C_NAME.findall(path.read_text()))
    return names


def draw(name, count, seed):
    """Deterministic (args, answer) rows for one relation."""

    rel = RELATIONS[name]
    rng = random.Random("%s:%s" % (seed, name))
    rows = []
    for _ in range(count):
        params, _question = rel.gen(rng)
        args = [str(p) for p in params]
        answer = rel.solve(*params)
        if "|" in answer or any("|" in a for a in args):
            raise SystemExit("%s: a '|' in a case would break the fixture" % name)
        rows.append("%s|%s" % (" ".join(args), answer))
    return rows


def render(table):
    rows = []
    for name, cases in table:
        text = esc("|".join(cases))
        rows.append('\t{ "%s", "%s" },' % (name, text))
    return TEMPLATE.replace("__ROWS__", "\n".join(rows))


def esc(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def build_and_run():
    binary = RUNTIME / "test_parity"
    subprocess.run(["make", "-s", "test_parity"], cwd=RUNTIME, check=True)
    try:
        proc = subprocess.run(["./" + binary.name], cwd=RUNTIME,
                              capture_output=True, text=True)
    finally:
        # Not in .gitignore, so leaving it behind invites a binary into the
        # next commit; `make test_parity` rebuilds it on demand.
        binary.unlink(missing_ok=True)
    sys.stdout.write(proc.stdout)
    sys.stderr.write(proc.stderr)
    counts = {}
    for line in proc.stdout.splitlines():
        m = re.match(r"^(\S+)\s+(\d+) cases, (\d+) mismatches$", line)
        if m and m.group(1) in RELATIONS:
            counts[m.group(1)] = (int(m.group(2)), int(m.group(3)))
    total = re.match(r"^TOTAL (\d+) cases, (\d+) mismatches$",
                     proc.stdout.splitlines()[-1] if proc.stdout else "")
    return counts, total


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--n", type=int, default=24,
                    help="instances per relation (default 24)")
    ap.add_argument("--seed", default="parity",
                    help="seed for the instance RNG (default 'parity')")
    ap.add_argument("--write-only", action="store_true",
                    help="regenerate the C table without building or running it")
    args = ap.parse_args()

    c_names = c_solver_names()
    py_names = set(RELATIONS)
    missing = sorted(py_names - c_names)
    orphan = sorted(c_names - py_names)

    print("relations with no C solver (%d):" % len(missing))
    print("  " + (", ".join(missing) if missing else "none"))
    print("C solvers with no relation (%d):" % len(orphan))
    print("  " + (", ".join(orphan) if orphan else "none"))

    table = []
    for name in sorted(py_names & c_names):
        cases = draw(name, args.n, args.seed)
        if len("|".join(cases)) >= MAX_ROWS:
            raise SystemExit("%s: %d rows exceed the %d-byte fixture limit"
                             % (name, args.n, MAX_ROWS))
        table.append((name, cases))

    GENERATED.write_text(render(table))
    print("wrote %s: %d relations, %d instances"
          % (GENERATED.relative_to(ROOT), len(table), len(table) * args.n))
    if args.write_only:
        return 0

    counts, total = build_and_run()
    if total is None:
        print("parity: the test binary printed no total")
        return 1

    by_subject = {}
    for name, (cases, bad) in counts.items():
        acc = by_subject.setdefault(RELATIONS[name].subject, [0, 0, 0])
        acc[0] += 1
        acc[1] += cases
        acc[2] += bad
    for subject in sorted(by_subject):
        rels, cases, bad = by_subject[subject]
        print("%-10s %3d relations %5d cases %d mismatches"
              % (subject, rels, cases, bad))

    total_cases, total_bad = int(total.group(1)), int(total.group(2))
    print("parity: %d cases, %d mismatches, %d gap(s)"
          % (total_cases, total_bad, len(missing) + len(orphan)))
    return 0 if total_bad == 0 and not missing and not orphan else 1


if __name__ == "__main__":
    sys.exit(main())
