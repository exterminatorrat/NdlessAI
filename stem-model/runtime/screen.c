static int glyph(uint16_t *fb, int x, int y, int ch, uint16_t c)
{
	const uint8_t *gl;

	if (ch >= 'a' && ch <= 'z')
		ch -= 32;
	if (ch < 32 || ch > 95)
		ch = '?';
	gl = gfont[ch - 32];
	for (int col = 0; col < SCREEN_GLYPH_W; col++)
		for (int row = 0; row < SCREEN_GLYPH_H; row++)
			if (gl[col] & (1 << row))
				screen_px(fb, x + col, y + row, c);
	return SCREEN_ADVANCE;
}

void screen_px(uint16_t *fb, int x, int y, uint16_t c)
{
	if (x >= 0 && x < SCREEN_W && y >= 0 && y < SCREEN_HEIGHT)
		fb[y * SCREEN_W + x] = c;
}

void screen_clear(uint16_t *fb, uint16_t c)
{
	for (int i = 0; i < SCREEN_W * SCREEN_HEIGHT; i++)
		fb[i] = c;
}

void screen_text(uint16_t *fb, int x, int y, const char *s, uint16_t c)
{
	if (!s)
		return;
	for (; *s; s++)
		x += glyph(fb, x, y, (unsigned char)*s, c);
}

void screen_fill(uint16_t *fb, int x, int y, int w, int h, uint16_t c)
{
	for (int row = 0; row < h; row++)
		for (int col = 0; col < w; col++)
			screen_px(fb, x + col, y + row, c);
}

void screen_rect(uint16_t *fb, int x, int y, int w, int h, uint16_t c)
{
	screen_hline(fb, x, y, w, c);
	screen_hline(fb, x, y + h - 1, w, c);
	for (int row = 0; row < h; row++) {
		screen_px(fb, x, y + row, c);
		screen_px(fb, x + w - 1, y + row, c);
	}
}

void screen_hline(uint16_t *fb, int x, int y, int w, uint16_t c)
{
	for (int i = 0; i < w; i++)
		screen_px(fb, x + i, y, c);
}

void screen_line(uint16_t *fb, int x0, int y0, int x1, int y1, uint16_t c)
{
	int dx = x1 - x0, dy = y1 - y0;
	int sx = dx < 0 ? -1 : 1, sy = dy < 0 ? -1 : 1;
	int err;

	if (dx < 0)
		dx = -dx;
	if (dy < 0)
		dy = -dy;
	err = dx - dy;
	for (;;) {
		int e2;

		screen_px(fb, x0, y0, c);
		if (x0 == x1 && y0 == y1)
			break;
		e2 = 2 * err;
		if (e2 > -dy) {
			err -= dy;
			x0 += sx;
		}
		if (e2 < dx) {
			err += dx;
			y0 += sy;
		}
	}
}

int screen_text_w(const char *s)
{
	return s ? (int)strlen(s) * SCREEN_ADVANCE : 0;
}

int screen_text_fit(const char *s, int px)
{
	int n = 0;

	if (!s || px <= 0)
		return 0;
	while (s[n] && (n + 1) * SCREEN_ADVANCE <= px)
		n++;
	return n;
}
